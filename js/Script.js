function setLanguage(lang) {
  const activeLang = ["fr", "en", "de"].includes(lang) ? lang : "fr";
  document.documentElement.lang = activeLang;

  try {
    localStorage.setItem("portfolio_lang", activeLang);
  } catch (e) {
    // Ignorer si le stockage est indisponible
  }

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const entry = i18nItems[key];
    if (entry && entry[activeLang]) {
      el.textContent = entry[activeLang];
    }
  });

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === activeLang);
  });
}

function initFilters() {
  const buttons = document.querySelectorAll(".filter-btn");
  const cards = document.querySelectorAll(".project-card");

  buttons.forEach((btn) => {
    btn.addEventListener("click", () => {
      const filter = btn.getAttribute("data-filter");
      buttons.forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");

      cards.forEach((card) => {
        const categories = (card.getAttribute("data-category") || "")
          .trim()
          .split(/\s+/);
        const show = filter === "all" || categories.includes(filter);
        card.classList.toggle("is-hidden", !show);
      });
    });
  });
}

function initVideoModal() {
  const triggers = document.querySelectorAll("[data-video-src]");
  if (!triggers.length) return;

  const modal = document.createElement("div");
  modal.className = "video-modal";
  modal.setAttribute("aria-hidden", "true");
  modal.innerHTML = `
    <div class="video-modal__backdrop" data-close-modal></div>
    <div class="video-modal__dialog" role="dialog" aria-modal="true">
      <button type="button" class="video-modal__close" data-close-modal aria-label="Fermer">&times;</button>
      <div class="video-modal__body"></div>
    </div>
  `;
  document.body.appendChild(modal);

  const body = modal.querySelector(".video-modal__body");

  function openModal(src) {
    body.innerHTML = "";
    const isDirectVideo = /\.(mp4|webm|ogg)(\?.*)?$/i.test(src);

    if (isDirectVideo) {
      const video = document.createElement("video");
      video.src = src;
      video.controls = true;
      video.autoplay = true;
      body.appendChild(video);
    } else {
      const iframe = document.createElement("iframe");
      iframe.src = src;
      iframe.allow = "accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture";
      iframe.allowFullscreen = true;
      body.appendChild(iframe);
    }

    modal.classList.add("is-open");
    modal.setAttribute("aria-hidden", "false");
  }

  function closeModal() {
    modal.classList.remove("is-open");
    modal.setAttribute("aria-hidden", "true");
    body.innerHTML = "";
  }

  triggers.forEach((btn) => {
    btn.addEventListener("click", (e) => {
      e.preventDefault();
      const src = btn.getAttribute("data-video-src");
      if (src) openModal(src);
    });
  });

  modal.querySelectorAll("[data-close-modal]").forEach((el) => {
    el.addEventListener("click", closeModal);
  });

  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && modal.classList.contains("is-open")) {
      closeModal();
    }
  });
}

function initPrintButtons() {
  const buttons = document.querySelectorAll("[data-print-target]");
  if (!buttons.length) return;

  function cleanupPrint() {
    document.body.classList.remove("printing-section");
    document.querySelectorAll(".print-target").forEach((el) => {
      el.classList.remove("print-target");
    });
  }

  window.addEventListener("afterprint", cleanupPrint);

  buttons.forEach((btn) => {
    btn.addEventListener("click", () => {
      cleanupPrint();
      const targetSelector = btn.getAttribute("data-print-target");
      if (targetSelector && targetSelector !== "all") {
        const targetEl = document.querySelector(targetSelector);
        if (targetEl) {
          targetEl.classList.add("print-target");
          document.body.classList.add("printing-section");
        }
      }
      window.print();
    });
  });
}

document.addEventListener("DOMContentLoaded", () => {
  let saved = null;
  try {
    saved = localStorage.getItem("portfolio_lang");
  } catch (e) {
    saved = null;
  }

  const browserLang = (navigator.language || "fr").slice(0, 2).toLowerCase();
  const initialLang = saved || (["fr", "en", "de"].includes(browserLang) ? browserLang : "fr");

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.addEventListener("click", () => setLanguage(btn.getAttribute("data-lang")));
  });

  setLanguage(initialLang);
  initFilters();
  initVideoModal();
  initPrintButtons();
});
